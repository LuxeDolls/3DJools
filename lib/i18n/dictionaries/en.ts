/* Widen the `as const` literal types (e.g. "Sign in") to their general types
   (string) so translated dictionaries only need to match the SHAPE of `en`,
   not its exact English string values. */
type Widen<T> = T extends string
  ? string
  : T extends number
    ? number
    : T extends boolean
      ? boolean
      : T extends readonly (infer U)[]
        ? readonly Widen<U>[]
        : { -readonly [K in keyof T]: Widen<T[K]> }

export type Dictionary = Widen<typeof en>
